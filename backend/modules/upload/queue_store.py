import json
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row


def _connect(database_url):
    if not database_url:
        raise ValueError("DATABASE_URL belum diatur.")

    return psycopg.connect(database_url, row_factory=dict_row)


def initialize_queue(database_url):
    """Buat tabel antrean dan invoice jika belum ada, serta lengkapi kolom lama."""
    with _connect(database_url) as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS queue_items (
                queue_number BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                document_id TEXT NOT NULL UNIQUE,
                uploaded_by_user_id BIGINT
                    REFERENCES users(user_id) ON DELETE SET NULL,
                company_id BIGINT
                    REFERENCES companies(company_id) ON DELETE RESTRICT,
                status TEXT NOT NULL,
                stage TEXT NOT NULL,
                stage_step INTEGER NOT NULL DEFAULT 0,
                stage_total INTEGER NOT NULL DEFAULT 3,
                queued_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                previewed_at TEXT,
                error_message TEXT
            )
            """
        )

        connection.execute(
            """
            ALTER TABLE queue_items
            ADD COLUMN IF NOT EXISTS uploaded_by_user_id BIGINT
                REFERENCES users(user_id) ON DELETE SET NULL
            """
        )

        connection.execute(
            """
            ALTER TABLE queue_items
            ADD COLUMN IF NOT EXISTS company_id BIGINT
                REFERENCES companies(company_id) ON DELETE RESTRICT
            """
        )

        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_queue_items_company_queue
            ON queue_items (company_id, queue_number DESC)
            """
        )

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS invoice_records (
                document_id TEXT NOT NULL
                    REFERENCES queue_items(document_id) ON DELETE CASCADE,
                invoice_index INTEGER NOT NULL,
                data JSONB NOT NULL,
                validation JSONB NOT NULL,
                status TEXT NOT NULL,
                previewed BOOLEAN NOT NULL DEFAULT FALSE,
                PRIMARY KEY (document_id, invoice_index)
            )
            """
        )

        now = datetime.now(timezone.utc).isoformat()
        connection.execute(
            """
            UPDATE queue_items
            SET status = 'QUEUED',
                stage = 'Menunggu giliran',
                stage_step = 0,
                updated_at = %s
            WHERE status = 'PROCESSING'
            """,
            (now,),
        )


def list_accessible_companies(database_url, user_id):
    """Ambil perusahaan aktif yang aksesnya sudah diberikan admin kepada user."""
    with _connect(database_url) as connection:
        rows = connection.execute(
            """
            SELECT
                c.company_id,
                c.company_code,
                c.company_name
            FROM user_company_access AS access
            JOIN companies AS c
                ON c.company_id = access.company_id
            WHERE access.user_id = %s
              AND c.is_active = TRUE
            ORDER BY c.company_name
            """,
            (user_id,),
        ).fetchall()

    return [dict(row) for row in rows]


def user_can_access_company(database_url, user_id, company_id):
    """Periksa ulang akses perusahaan di sisi server."""
    if user_id is None or company_id is None:
        return False

    with _connect(database_url) as connection:
        row = connection.execute(
            """
            SELECT 1
            FROM user_company_access AS access
            JOIN companies AS c
                ON c.company_id = access.company_id
            WHERE access.user_id = %s
              AND c.company_id = %s
              AND c.is_active = TRUE
            LIMIT 1
            """,
            (user_id, company_id),
        ).fetchone()

    return row is not None


def enqueue_document(
    database_url,
    document_id,
    uploaded_by_user_id,
    company_id,
):
    """
    Masukkan dokumen ke antrean hanya jika user memiliki akses ke perusahaan
    aktif yang dipilih.
    """
    if uploaded_by_user_id is None:
        raise ValueError("Pengguna yang mengunggah dokumen tidak diketahui.")

    if company_id is None:
        raise ValueError("Perusahaan harus dipilih sebelum dokumen diunggah.")

    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        row = connection.execute(
            """
            INSERT INTO queue_items (
                document_id,
                uploaded_by_user_id,
                company_id,
                status,
                stage,
                stage_step,
                stage_total,
                queued_at,
                updated_at
            )
            SELECT
                %s,
                %s,
                c.company_id,
                'QUEUED',
                'Menunggu giliran',
                0,
                3,
                %s,
                %s
            FROM companies AS c
            JOIN user_company_access AS access
                ON access.company_id = c.company_id
            WHERE c.company_id = %s
              AND c.is_active = TRUE
              AND access.user_id = %s
            RETURNING queue_number
            """,
            (
                document_id,
                uploaded_by_user_id,
                now,
                now,
                company_id,
                uploaded_by_user_id,
            ),
        ).fetchone()

        if row is None:
            raise PermissionError(
                "Akses ke perusahaan tersebut belum diberikan oleh System Admin."
            )

        return row["queue_number"]


def claim_next_document(database_url):
    """Ambil satu dokumen QUEUED dengan aman untuk diproses worker."""
    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        row = connection.execute(
            """
            SELECT queue_number
            FROM queue_items
            WHERE status = 'QUEUED'
            ORDER BY queue_number
            LIMIT 1
            FOR UPDATE SKIP LOCKED
            """
        ).fetchone()

        if row is None:
            return None

        claimed = connection.execute(
            """
            UPDATE queue_items
            SET status = 'PROCESSING',
                stage = 'Menyiapkan dokumen',
                stage_step = 0,
                updated_at = %s
            WHERE queue_number = %s
            RETURNING *
            """,
            (now, row["queue_number"]),
        ).fetchone()

        return dict(claimed) if claimed else None


def update_queue_item(
    database_url,
    document_id,
    *,
    status=None,
    stage=None,
    stage_step=None,
    error_message=None,
):
    """Perbarui status pemrosesan dokumen."""
    values = {"updated_at": datetime.now(timezone.utc).isoformat()}

    if status is not None:
        values["status"] = status
    if stage is not None:
        values["stage"] = stage
    if stage_step is not None:
        values["stage_step"] = stage_step
    if error_message is not None:
        values["error_message"] = str(error_message)[:1000]

    assignments = ", ".join(f"{column} = %s" for column in values)
    parameters = [*values.values(), document_id]

    with _connect(database_url) as connection:
        connection.execute(
            f"""
            UPDATE queue_items
            SET {assignments}
            WHERE document_id = %s
            """,
            parameters,
        )


def save_invoice_records(database_url, document_id, records):
    """Simpan ulang hasil ekstraksi dan validasi invoice untuk dokumen."""
    with _connect(database_url) as connection:
        connection.execute(
            "DELETE FROM invoice_records WHERE document_id = %s",
            (document_id,),
        )

        for index, record in enumerate(records):
            connection.execute(
                """
                INSERT INTO invoice_records (
                    document_id,
                    invoice_index,
                    data,
                    validation,
                    status,
                    previewed
                )
                VALUES (%s, %s, %s::jsonb, %s::jsonb, %s, %s)
                """,
                (
                    document_id,
                    index,
                    json.dumps(record.get("data", {}), ensure_ascii=False),
                    json.dumps(
                        record.get("validation", {}),
                        ensure_ascii=False,
                    ),
                    record.get("status", "READY_FOR_REVIEW"),
                    bool(record.get("previewed", False)),
                ),
            )


def load_invoice_records(database_url, document_id):
    """Muat semua invoice dalam urutan indeksnya."""
    with _connect(database_url) as connection:
        rows = connection.execute(
            """
            SELECT data, validation, status, previewed
            FROM invoice_records
            WHERE document_id = %s
            ORDER BY invoice_index
            """,
            (document_id,),
        ).fetchall()

    return [dict(row) for row in rows]


def mark_invoice_previewed(database_url, document_id, invoice_index):
    with _connect(database_url) as connection:
        connection.execute(
            """
            UPDATE invoice_records
            SET previewed = TRUE
            WHERE document_id = %s
              AND invoice_index = %s
            """,
            (document_id, invoice_index),
        )


def mark_previewed(database_url, document_id):
    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        connection.execute(
            """
            UPDATE queue_items
            SET previewed_at = COALESCE(previewed_at, %s),
                updated_at = %s
            WHERE document_id = %s
            """,
            (now, now, document_id),
        )


def list_queue_items(
    database_url,
    uploaded_by_user_id=None,
    company_ids=None,
):
    """
    Ambil antrean.

    - uploaded_by_user_id membatasi hasil ke dokumen milik uploader.
    - company_ids membatasi hasil ke perusahaan yang boleh diakses user.
    - company_ids=[] menghasilkan antrean kosong.
    """
    conditions = []
    parameters = []

    if uploaded_by_user_id is not None:
        conditions.append("q.uploaded_by_user_id = %s")
        parameters.append(uploaded_by_user_id)

    if company_ids is not None:
        allowed_company_ids = list(company_ids)

        if not allowed_company_ids:
            return []

        conditions.append("q.company_id = ANY(%s)")
        parameters.append(allowed_company_ids)

    where_clause = ""
    if conditions:
        where_clause = "WHERE " + " AND ".join(conditions)

    with _connect(database_url) as connection:
        rows = connection.execute(
            f"""
            SELECT
                q.*,
                c.company_code,
                c.company_name
            FROM queue_items AS q
            LEFT JOIN companies AS c
                ON c.company_id = q.company_id
            {where_clause}
            ORDER BY q.queue_number DESC
            """,
            parameters,
        ).fetchall()

    return [dict(row) for row in rows]