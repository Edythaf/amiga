import json
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row


def _connect(database_url):
    if not database_url:
        raise ValueError("DATABASE_URL belum diatur.")

    return psycopg.connect(database_url, row_factory=dict_row)


def initialize_queue(database_url):
    with _connect(database_url) as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS queue_items (
                queue_number BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                document_id TEXT NOT NULL UNIQUE,
                status TEXT NOT NULL,
                stage TEXT NOT NULL,
                stage_step INTEGER NOT NULL DEFAULT 0,
                stage_total INTEGER NOT NULL DEFAULT 3,
                queued_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                previewed_at TEXT,
                error_message TEXT
            )
            """
        )

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS invoice_records (
                document_id TEXT NOT NULL
                    REFERENCES queue_items(document_id) ON DELETE CASCADE,
                invoice_index INTEGER NOT NULL,
                data JSONB NOT NULL,
                validation JSONB NOT NULL,
                status TEXT NOT NULL,
                previewed BOOLEAN NOT NULL DEFAULT FALSE,
                PRIMARY KEY (document_id, invoice_index)
            )
            """
        )

        now = datetime.now(timezone.utc).isoformat()
        connection.execute(
            """
            UPDATE queue_items
            SET status = 'QUEUED',
                stage = 'Menunggu giliran',
                stage_step = 0,
                updated_at = %s
            WHERE status = 'PROCESSING'
            """,
            (now,),
        )


def enqueue_document(database_url, document_id):
    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        row = connection.execute(
            """
            INSERT INTO queue_items (
                document_id, status, stage, stage_step,
                stage_total, queued_at, updated_at
            )
            VALUES (%s, 'QUEUED', 'Menunggu giliran', 0, 3, %s, %s)
            RETURNING queue_number
            """,
            (document_id, now, now),
        ).fetchone()

        return row["queue_number"]


def claim_next_document(database_url):
    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        row = connection.execute(
            """
            SELECT queue_number
            FROM queue_items
            WHERE status = 'QUEUED'
            ORDER BY queue_number
            LIMIT 1
            FOR UPDATE SKIP LOCKED
            """
        ).fetchone()

        if row is None:
            return None

        claimed = connection.execute(
            """
            UPDATE queue_items
            SET status = 'PROCESSING',
                stage = 'Menyiapkan dokumen',
                stage_step = 0,
                updated_at = %s
            WHERE queue_number = %s
            RETURNING *
            """,
            (now, row["queue_number"]),
        ).fetchone()

        return dict(claimed)


def update_queue_item(
    database_url,
    document_id,
    *,
    status=None,
    stage=None,
    stage_step=None,
    error_message=None,
):
    values = {"updated_at": datetime.now(timezone.utc).isoformat()}

    if status is not None:
        values["status"] = status
    if stage is not None:
        values["stage"] = stage
    if stage_step is not None:
        values["stage_step"] = stage_step
    if error_message is not None:
        values["error_message"] = str(error_message)[:1000]

    assignments = ", ".join(f"{column} = %s" for column in values)
    parameters = [*values.values(), document_id]

    with _connect(database_url) as connection:
        connection.execute(
            f"""
            UPDATE queue_items
            SET {assignments}
            WHERE document_id = %s
            """,
            parameters,
        )


def save_invoice_records(database_url, document_id, records):
    with _connect(database_url) as connection:
        connection.execute(
            "DELETE FROM invoice_records WHERE document_id = %s",
            (document_id,),
        )

        for index, record in enumerate(records):
            connection.execute(
                """
                INSERT INTO invoice_records (
                    document_id, invoice_index, data,
                    validation, status, previewed
                )
                VALUES (%s, %s, %s::jsonb, %s::jsonb, %s, %s)
                """,
                (
                    document_id,
                    index,
                    json.dumps(record.get("data", {}), ensure_ascii=False),
                    json.dumps(
                        record.get("validation", {}),
                        ensure_ascii=False,
                    ),
                    record.get("status", "READY_FOR_REVIEW"),
                    bool(record.get("previewed", False)),
                ),
            )


def load_invoice_records(database_url, document_id):
    with _connect(database_url) as connection:
        rows = connection.execute(
            """
            SELECT data, validation, status, previewed
            FROM invoice_records
            WHERE document_id = %s
            ORDER BY invoice_index
            """,
            (document_id,),
        ).fetchall()

    return [dict(row) for row in rows]


def mark_invoice_previewed(database_url, document_id, invoice_index):
    with _connect(database_url) as connection:
        connection.execute(
            """
            UPDATE invoice_records
            SET previewed = TRUE
            WHERE document_id = %s AND invoice_index = %s
            """,
            (document_id, invoice_index),
        )


def mark_previewed(database_url, document_id):
    now = datetime.now(timezone.utc).isoformat()

    with _connect(database_url) as connection:
        connection.execute(
            """
            UPDATE queue_items
            SET previewed_at = COALESCE(previewed_at, %s),
                updated_at = %s
            WHERE document_id = %s
            """,
            (now, now, document_id),
        )


def list_queue_items(database_url):
    with _connect(database_url) as connection:
        rows = connection.execute(
            """
            SELECT *
            FROM queue_items
            ORDER BY queue_number DESC
            """
        ).fetchall()

    return [dict(row) for row in rows]